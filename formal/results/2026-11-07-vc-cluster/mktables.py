#!/usr/bin/env python3
"""Build tables-vc.md from drive.out: one row per recorded run of the
2026-11-07 cluster batch, with the cfg's md5 and the spec's md5 as the
driver printed it.  Lines the driver did not write (hand notes: STOPPED,
NOT A RESULT) are kept verbatim under the table.

  python3 mktables.py > tables-vc.md
"""
import hashlib
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))


def md5(path):
    try:
        return hashlib.md5(open(path, 'rb').read()).hexdigest()[:8]
    except OSError:
        return '-'


def cfg_path(name):
    for d in ('cfg', 'cfg-resize'):
        p = os.path.join(HERE, d, name + '.cfg')
        if os.path.exists(p):
            return p
    p = os.path.join(HERE, 'cfg-%s.cfg.deferred' % name)
    return p if os.path.exists(p) else None


rows, notes = [], []
for line in open(os.path.join(HERE, 'drive.out')):
    line = line.rstrip('\n')
    m = re.match(r'(\S+) rc=(\d+) capped=(\d) wall=(\d+) md5=([0-9a-f]+) ?(.*)$', line)
    if not m:
        notes.append(line)
        continue
    name, rc, capped, wall, spec, rest = m.groups()
    d = re.search(r'([\d]+) distinct states found\. Depth (\d+)', rest)
    if 'violated' in rest:
        inv = re.search(r'Invariant (\S+) is violated', rest).group(1)
        verdict = 'VIOLATED `%s`' % inv
    elif 'Error:' in rest:
        verdict = 'stopped by an error, bounded: %s' % re.search(r'Error: ([^(]*)', rest).group(1).strip()
    elif d:
        verdict = 'HOLD, full space'
    elif capped == '1':
        verdict = 'bounded (capped)'
    else:
        verdict = 'error (rc %s)' % rc
    if d and 'Error:' not in rest:
        size = '%s states, depth %s' % (format(int(d.group(1)), ','), d.group(2))
    elif d:
        size = 'to depth %s, %s states' % (d.group(2), format(int(d.group(1)), ','))
    else:
        p = re.findall(r'depth (\d+), \d+ generated, (\d+) distinct', rest)
        size = ('to depth %s, %s states' % (p[-1][0], format(int(p[-1][1]), ','))) if p else '-'
    if 'violated' in rest:
        v = re.search(r'(\d+) distinct states found\. Depth (\d+)', rest)
        size = 'depth %s (%s states)' % (v.group(2), format(int(v.group(1)), ','))
    c = cfg_path(name)
    t = re.search(r'Checked in ([\d.]+)s', rest)
    rows.append('| %s | `%s` | `%s` | %s | %s | %s | %s s |' % (
        name, md5(c) if c else '-', spec[:8], verdict, size,
        ('%d s' % float(t.group(1))) if t else '-', wall))

print('# The 2026-11-07 cluster batch (vc01NN, tla-mc 0.3.0 `-cluster`, compiled)\n')
print('Generated by `mktables.py` from `drive.out`. Spec md5s: `61ae6829` FlintCatchupS rev 17,')
print('`9f274f80` FlintCatchupSSym, `35a7ec38` FlintCatchupSSymV, `a202f0f8` FlintCatchupSR rev 18.')
print('Capped and stopped runs are bounded: "to depth N" is the last level closed. "Checked in" is\nnode 0\'s search time; the driver\'s wall adds the build, the copy and any wait for hung ssh sessions.\n')
print('| Run | cfg | spec | Verdict | Size | Checked in | Driver wall |')
print('|---|---|---|---|---|---|---|')
for r in rows:
    print(r)
print('\nHand notes in drive.out:\n')
for n in notes:
    print('- ' + n)
