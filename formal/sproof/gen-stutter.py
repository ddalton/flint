# gen-stutter.py: writes 60-stutter.tla-part from the IndInv groups (one step per conjunct, its frame F_<X>), so a new
# conjunct is a list edit.  Run after changing 40-ind-base's groups.
import os, re
D = os.path.dirname(os.path.abspath(__file__))
J = ['DueHold', 'JHoldAtt:J_HoldAtt', 'Rel', 'Cur', 'ZxOut', 'Aseq', 'SeqSync', 'MemRel', 'RelHold', 'NoAckBad', 'M0',
     'RelValid', 'MinorRel', 'RelInSync', 'ViewIn', 'ViewOut', 'SoleSeq', 'GenBound', 'ZGen']
T = ['RangesS:I_RangesS', 'Lineage:I_Lineage', 'Chain:I_Chain', 'Pend:I_Pend', 'MembersS:I_MembersS', 'HoldAtt:I_HoldAtt',
     'PendSeen:I_PendSeen', 'Vers:I_Vers', 'Reverted:I_Reverted', 'HeadPend:I_HeadPend', 'Session:I_Session',
     'TC:Inv_TrustComplete', 'NoBadLoss:I_NoBadLoss', 'AckedHeld:Inv_AckedHeld']
S = ['AckedEverS:I_AckedEverS', 'LegalS:I_LegalS', 'WHiS:I_WHiS', 'AckMono:I_AckMono', 'HeadLoS:I_HeadLoS', 'FreshS:I_FreshS']
def steps(lst, grp, pre, lvl):
    out = []
    for i, e in enumerate(lst, 1):
        f, c = (e.split(':') + [None])[:2]
        c = c or f'{pre}{f}'
        out.append(f'  <2>{i}. {c}\' BY <1>0, <1>u, F_{f} DEF {grp}')
    out.append(f'  <2>. QED BY ' + ', '.join(f'<2>{i}' for i in range(1, len(lst) + 1)) + f' DEF {grp}')
    return '\n'.join(out)
txt = f'''(* (S) Stuttering keeps the invariant (generated by sproof/gen-stutter.py). *)

LEMMA I_Stutter == ASSUME IndInv, UNCHANGED vars PROVE IndInv'
<1>0. TypeOK /\\ IndJ /\\ IndT /\\ IndS BY IndSplit
<1>u. /\\ UNCHANGED <<ver, head, hAl, hPar, sPres, sCon, sAl, sPar, anc, recorded, nextSeq>>
      /\\ UNCHANGED <<cutK, cutTgt, cutDone, cutGone, members, attached, path, dState, mark>>
      /\\ UNCHANGED <<reverted, sb, pin, riskRec, pend, acked, fails, badAdmit, badLoss, ackedEver>>
      /\\ UNCHANGED <<used, tainted, floor, mustRev, restamp, cfgAt, conf, tr, htr, zx, cutAck>>
      /\\ UNCHANGED <<stamp, nseq, aseq, agen, asize, rgenA, rmemA, hold, due, sole, zseq, zgen, zsize, zm0>>
      /\\ UNCHANGED <<zrgen, zrmem, zst, badAck, zAcked, zfreed, zLeg, zjv, zexcl, postMove, legalJ>>
      /\\ UNCHANGED <<riskTail, vouched, tornMarked, tornServed, tornBare, zpost>>
  BY DEF vars
<1>1. TypeOKT' BY <1>0, <1>u, TypeOKParts, Groups, GroupsP, C_Scalar, C_Sets, C_Leg, C_Head, C_Snap, C_Pend, C_Tie, C_Trust
             DEF tieVars, trustVars
<1>2. TyStampS' BY <1>0, <1>u, TypeOKParts, TyStampSplit, TyStampSplitP, C_StA, C_Gh DEF stampVars, sGhost
<1>3. TypeOK' BY <1>1, <1>2, TypeOKPartsP
<1>4. IndJ'
{steps(J, 'IndJ', 'J_', 2)}
<1>5. IndT'
{steps(T, 'IndT', 'I_', 2)}
<1>6. IndS'
{steps(S, 'IndS', 'I_', 2)}
<1>. QED BY <1>3, <1>4, <1>5, <1>6, IndSplitP
'''
# IndNew (41-ind-new): each conjunct with its frame F_<X> (as 41-ind-new names them)
NEWF = open(f'{D}/41-ind-new.tla-part').read()
NEW = re.findall(r"^LEMMA (F_\w+) == (\w+) /\\ UNCHANGED", NEWF, re.M)
txt += """
LEMMA I_StutterAll == ASSUME IndAll, UNCHANGED vars PROVE IndAll'
<1>0. IndInv /\\ IndNew BY DEF IndAll
<1>1. IndInv' BY <1>0, I_Stutter
<1>u. /\\ UNCHANGED <<ver, head, hAl, hPar, sPres, sCon, sAl, sPar, anc, recorded, nextSeq>>
      /\\ UNCHANGED <<cutK, cutTgt, cutDone, cutGone, members, attached, path, dState, mark>>
      /\\ UNCHANGED <<reverted, sb, pin, riskRec, pend, acked, fails, badAdmit, badLoss, ackedEver>>
      /\\ UNCHANGED <<used, tainted, floor, mustRev, restamp, cfgAt, conf, tr, htr, zx, cutAck>>
      /\\ UNCHANGED <<stamp, nseq, aseq, agen, asize, rgenA, rmemA, hold, due, sole, zseq, zgen, zsize, zm0>>
      /\\ UNCHANGED <<zrgen, zrmem, zst, badAck, zAcked, zfreed, zLeg, zjv, zexcl, postMove, legalJ>>
      /\\ UNCHANGED <<riskTail, vouched, tornMarked, tornServed, tornBare, zpost>>
  BY DEF vars
<1>n. """ + "IndNew'\n" + "\n".join(f"  <2>{i}. {c}' BY <1>0, <1>u, IndNewSplit, {f}" for i, (f, c) in enumerate(NEW, 1)) + \
"\n  <2>. QED BY " + ", ".join(f"<2>{i}" for i in range(1, len(NEW) + 1)) + ", IndNewSplitP" + """
<1>. QED BY <1>1, <1>n DEF IndAll
"""
open(f'{D}/60-stutter.tla-part', 'w').write(txt)
print('wrote 60-stutter.tla-part', len(J), len(T), len(S))
